function stationColor(lines) {
  if (!lines) return '#808183';
  const first = lines.trim().split(/[\s,\u00b7\-]+/)[0].toUpperCase();
  return SUBWAY_LINE_COLORS[first] || '#808183';
}

function stationDist(lat1, lng1, lat2, lng2) {
  const R = 6371000;
  const dLat = (lat2 - lat1) * Math.PI / 180;
  const dLng = (lng2 - lng1) * Math.PI / 180;
  const a = Math.sin(dLat/2)**2 +
            Math.cos(lat1*Math.PI/180)*Math.cos(lat2*Math.PI/180)*Math.sin(dLng/2)**2;
  return R * 2 * Math.atan2(Math.sqrt(a), Math.sqrt(1-a));
}

function walkMinutes(metres) {
  const mins = Math.round(metres / 83);
  return mins < 1 ? '< 1 min' : `${mins} min`;
}

function nearestStations(lat, lng, n = 2) {
  return SUBWAY_STATIONS
    .map(s => ({ ...s, dist: stationDist(lat, lng, s.lat, s.lng) }))
    .sort((a, b) => a.dist - b.dist)
    .slice(0, n);
}

